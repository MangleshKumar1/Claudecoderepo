#!/usr/bin/env bash
# Put a backup's DATA back into a YORVIA database whose tables already exist.
#
#   TARGET_URL='postgresql://...' ./scripts/restore-db.sh backups/yorvia-20261030-120000.dump
#
# Before you run it:
#   * The tables must exist in the target. On a new Supabase project, run the SQL files in web/supabase/
#     in order first (README, Step 1). On plain Postgres, run scripts/plain-postgres-auth-shim.sql and then those files.
#   * The login accounts the data refers to must exist in the target (same user ids). Recovering inside the same
#     Supabase project is fine, since the accounts are still there. To move to a different server, also pass the
#     accounts file made with INCLUDE_ACCOUNTS=1:   ACCOUNTS_FILE=backups/yorvia-...-accounts.dump
#
# What it does: in ONE all-or-nothing step it empties the app tables in the target, then loads the backup's rows.
# If anything fails, nothing is changed. It does NOT touch Supabase's own login tables unless you pass ACCOUNTS_FILE.
set -euo pipefail

: "${TARGET_URL:?Set TARGET_URL to the database you are restoring INTO}"
file="${1:?Give the backup file to restore}"
[ -f "$file" ] || { echo "No such file: $file"; exit 1; }
for tool in pg_restore psql; do command -v "$tool" >/dev/null || { echo "$tool not found. Install the PostgreSQL client tools."; exit 1; }; done
accounts="${ACCOUNTS_FILE:-}"
[ -z "$accounts" ] || [ -f "$accounts" ] || { echo "No such accounts file: $accounts"; exit 1; }

echo "About to REPLACE the data in the YORVIA tables of the database in TARGET_URL with the contents of $file."
[ -z "$accounts" ] || echo "It will also REPLACE the login accounts (auth.users) with those in $accounts."
if [ "${YES:-0}" != "1" ]; then read -r -p "Type yes to continue: " ok; [ "$ok" = "yes" ] || { echo "Cancelled."; exit 1; }; fi

tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT
{
  echo "-- generated by restore-db.sh"
  # 1. switch off the app's own triggers while loading, so old rows are not re-checked or re-notified
  cat <<'SQL'
do $$ declare r record; begin
  for r in select schemaname, tablename from pg_tables where schemaname = 'public' loop
    execute format('alter table %I.%I disable trigger user', r.schemaname, r.tablename);
  end loop;
SQL
  if [ -n "$accounts" ]; then
    echo "  if to_regclass('auth.users') is not null then alter table auth.users disable trigger user; end if;"
  fi
  # 2. empty the app tables (and accounts, only if an accounts file was given)
  cat <<'SQL'
  execute (select 'truncate table ' || string_agg(format('%I.%I', schemaname, tablename), ', ') || ' cascade' from pg_tables where schemaname = 'public');
end $$;
SQL
  if [ -n "$accounts" ]; then
    echo "truncate table auth.users cascade;"
    pg_restore --data-only --no-owner --no-privileges -f - "$accounts"
  fi
  # 3. load the rows, parents before children (the backup lists tables alphabetically, which would break the links between them)
  order="$(psql "$TARGET_URL" -At -v ON_ERROR_STOP=1 -q <<'SQL'
with recursive deps as (
  select c.relname as child, p.relname as parent
  from pg_constraint k join pg_class c on c.oid = k.conrelid join pg_class p on p.oid = k.confrelid
  where k.contype = 'f' and c.relnamespace = 'public'::regnamespace and p.relnamespace = 'public'::regnamespace and c.oid <> p.oid
), lvl(t, n) as (
  select tablename::text, 0 from pg_tables where schemaname = 'public'
  union all
  select d.child, l.n + 1 from lvl l join deps d on d.parent = l.t where l.n < 30
)
select t from lvl group by t order by max(n), t;
SQL
)"
  [ -n "$order" ] || { echo "Could not read the tables in the target database. Is the schema installed?" >&2; exit 1; }
  for t in $order; do
    pg_restore --data-only --no-owner --no-privileges --schema=public --table="$t" -f - "$file"
  done
  # 4. move the ID counters past the restored rows, then switch the triggers back on
  cat <<'SQL'
do $$ declare r record; begin
  for r in select table_name, column_name from information_schema.columns
           where table_schema = 'public' and (is_identity = 'YES' or column_default like 'nextval%') loop
    execute format('select setval(pg_get_serial_sequence(%L, %L), greatest((select coalesce(max(%I), 0) from public.%I), 1))',
                   'public.' || r.table_name, r.column_name, r.column_name, r.table_name);
  end loop;
end $$;
do $$ declare r record; begin
  for r in select schemaname, tablename from pg_tables where schemaname = 'public' loop
    execute format('alter table %I.%I enable trigger user', r.schemaname, r.tablename);
  end loop;
  if to_regclass('auth.users') is not null then alter table auth.users enable trigger user; end if;
end $$;
SQL
} > "$tmp"

if psql "$TARGET_URL" --single-transaction -v ON_ERROR_STOP=1 -q -f "$tmp"; then
  echo "Restore finished."
else
  echo
  echo "The restore failed and NOTHING was changed. Common causes:"
  echo " - a table or column is missing: run the SQL files in web/supabase/ (all of them, in order) on the target first."
  echo " - 'foreign key ... auth.users': the accounts the data refers to are not in the target. Pass ACCOUNTS_FILE=... when moving to a new server."
  exit 1
fi
